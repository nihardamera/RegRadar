"""The parse audit: what was read, how, and where text may have been lost.

Written from the manifest alone, so every number in corpus/AUDIT.md can be
recomputed from a committed file.
"""

from __future__ import annotations

import statistics
from collections import Counter
from collections.abc import Sequence
from typing import Any

from regradar.corpus.document import HTML_RECALL_FLOOR
from regradar.corpus.pdf import PAGE_PRECISION_FLOOR, PAGE_RECALL_FLOOR


def _share(count: int, total: int) -> str:
    return f"{count} / {total} ({100 * count / total:.1f}%)" if total else "0 / 0"


def _quantile(values: Sequence[float], q: float) -> float:
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, int(q * (len(ordered) - 1)))]


def summary(rows: Sequence[dict[str, Any]]) -> dict[str, Any]:
    corpus = [row for row in rows if row.get("in_corpus")]
    html_recall = [row["html_in_pdf_recall"] for row in corpus if "html_in_pdf_recall" in row]
    dates = sorted(row["date"] for row in corpus if row.get("date"))
    return {
        "selected": len(rows),
        "in_corpus": len(corpus),
        "status": dict(Counter(row["status"] for row in rows)),
        "text_source": dict(Counter(row["text_source"] for row in corpus)),
        "kind": dict(Counter(row["kind"] for row in corpus)),
        "department": dict(Counter(row.get("department") or "unknown" for row in corpus)),
        "year": dict(sorted(Counter(d[:4] for d in dates).items())),
        "date_range": [dates[0], dates[-1]] if dates else None,
        "pages": sum(row.get("pages", 0) for row in corpus),
        "tables": sum(row.get("tables", 0) for row in corpus),
        "with_circular_number": sum(1 for row in corpus if row.get("circular_number")),
        "with_reference": sum(1 for row in corpus if row.get("reference")),
        "with_date": len(dates),
        "with_department": sum(1 for row in corpus if row.get("department")),
        "with_addressees": sum(1 for row in corpus if row.get("addressees")),
        "html_compared": len(html_recall),
        "html_recall_min": min(html_recall) if html_recall else None,
        "html_recall_p05": _quantile(html_recall, 0.05) if html_recall else None,
        "html_recall_median": statistics.median(html_recall) if html_recall else None,
        "html_below_floor": [
            row["doc_id"]
            for row in corpus
            if row.get("html_in_pdf_recall", 1.0) < HTML_RECALL_FLOOR
        ],
        "low_recall_pages": {
            row["doc_id"]: row["low_recall_pages"] for row in corpus if row.get("low_recall_pages")
        },
        "repeated_text_pages": {
            row["doc_id"]: row["repeated_text_pages"]
            for row in corpus
            if row.get("repeated_text_pages")
        },
        "scanned_pages": {
            row["doc_id"]: row["scanned_pages"] for row in rows if row.get("scanned_pages")
        },
        "devanagari_heavy": [
            row["doc_id"] for row in corpus if row.get("devanagari_share", 0) > 0.3
        ],
        "garbled": [row["doc_id"] for row in corpus if row.get("garbled_share", 0) > 0.001],
    }


def render(rows: Sequence[dict[str, Any]]) -> str:
    s = summary(rows)
    n = s["in_corpus"]
    by_id = {row["doc_id"]: row for row in rows}

    def title(doc: str) -> str:
        return f"`{doc}` {by_id[doc]['title'][:90]}"

    lines = [
        "# Corpus parse audit",
        "",
        "Generated by `uv run python -m regradar.corpus.build audit` from",
        "[`manifest.jsonl`](manifest.jsonl). Do not edit by hand.",
        "",
        "## What was read",
        "",
        f"- Selected circulars: {s['selected']}. In the corpus: **{n}**.",
        f"- Outcome of every selected circular: {s['status']}.",
        f"- Text taken from: {s['text_source']}.",
        f"- Dates: {s['date_range'][0]} to {s['date_range'][1]}; by year {s['year']}."
        if s["date_range"]
        else "- Dates: none found.",
        f"- Kinds: {s['kind']}.",
        f"- Departments: {s['department']}.",
        f"- {s['pages']} PDF pages; {s['tables']} tables rendered as Markdown.",
        "",
        "## Metadata found",
        "",
        "| Field | Documents |",
        "| --- | --- |",
        f"| Circular number | {_share(s['with_circular_number'], n)} |",
        f"| Reference | {_share(s['with_reference'], n)} |",
        f"| Date | {_share(s['with_date'], n)} |",
        f"| Department | {_share(s['with_department'], n)} |",
        f"| Addressees | {_share(s['with_addressees'], n)} (Directions usually have none) |",
        "",
        "## Was any text dropped?",
        "",
        "Three checks, each independent of the others:",
        "",
        f"1. **Per page, against a second reader.** pypdf reads each page's text layer"
        f" with different code. Pages where PyMuPDF's output keeps less than"
        f" {PAGE_RECALL_FLOOR:.0%} of pypdf's distinct words: {len(s['low_recall_pages'])}"
        f" document(s).",
    ]
    lines += [f"   - {title(doc)}: pages {pages}" for doc, pages in s["low_recall_pages"].items()]
    lines += [
        f"   The same comparison the other way finds repeated text: pages where under"
        f" {PAGE_PRECISION_FLOOR:.0%} of PyMuPDF's words are in pypdf's (a table cell read"
        f" twice, for example): {len(s['repeated_text_pages'])} document(s).",
    ]
    lines += [
        f"   - {title(doc)}: pages {pages}" for doc, pages in s["repeated_text_pages"].items()
    ]
    lines += [
        f"2. **Per document, against the web page.** {s['html_compared']} documents also"
        " have the circular as HTML. Share of the HTML's words found in the PDF text:"
        + (
            f" min {s['html_recall_min']:.3f}, 5th percentile {s['html_recall_p05']:.3f},"
            f" median {s['html_recall_median']:.3f}. Below {HTML_RECALL_FLOOR:.0%}:"
            f" {len(s['html_below_floor'])}."
            if s["html_compared"]
            else " none to compare."
        ),
    ]
    lines += [f"   - {title(doc)}" for doc in s["html_below_floor"]]
    lines += [
        "3. **Pages with no text layer.** A page with under 40 characters of text and an"
        f" image over half of it is a scan. Documents with scanned pages:"
        f" {len(s['scanned_pages'])}.",
    ]
    lines += [f"   - {title(doc)}: pages {pages}" for doc, pages in s["scanned_pages"].items()]
    lines += [
        "",
        "Neither text reader can see words that exist only as pixels; check 3 is what",
        "catches those. A scanned PDF with an HTML version is read from the HTML; one",
        "without is listed above and left out (OCR is a stretch goal).",
        "",
        "## Other flags",
        "",
        f"- Mostly Devanagari (over 30% of characters): {s['devanagari_heavy'] or 'none'}."
        " Every circular has a Hindi letterhead and footer, which extract with wrong glyphs"
        " (not private-use characters, so the check below misses them); they are boilerplate"
        " and are stripped before chunking.",
        f"- Broken font encodings (private-use characters): {s['garbled'] or 'none'}.",
        "",
        "## Left out",
        "",
    ]
    left_out = [row for row in rows if not row.get("in_corpus")]
    for row in left_out:
        reason = row["status"]
        if row.get("duplicate_of"):
            reason += f" of `{row['duplicate_of']}`"
        if row.get("pdf_problem"):
            reason += f" ({row['pdf_problem']})"
        lines.append(f"- {title(row['doc_id'])}: {reason}")
    if not left_out:
        lines.append("- none")
    return "\n".join(lines) + "\n"
